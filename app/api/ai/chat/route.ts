import { NextResponse } from 'next/server';
import { processChatRequest } from '@/lib/ai/brain';

export const runtime = 'nodejs'; // Use nodejs so we don't have edge limits with supabase server clients

export async function POST(req: Request) {
  try {
    const { message, history } = await req.json();

    if (!message) {
      return NextResponse.json({ error: 'Message is required' }, { status: 400 });
    }

    // Call the Restaurant Brain
    const stream = await processChatRequest(message, history || []);

    // Return the custom readable stream as an SSE response
    return new Response(stream, {
      headers: {
        'Content-Type': 'text/event-stream',
        'Cache-Control': 'no-cache',
        'Connection': 'keep-alive',
      },
    });

  } catch (error: any) {
    console.error('API Error:', error);
    if (error.message === 'Unauthorized') {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }
    return NextResponse.json({ error: 'Internal Server Error' }, { status: 500 });
  }
}
